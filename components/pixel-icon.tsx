export type PixelName = keyof typeof SHAPES;

export function PixelIcon({
  name,
  className,
}: {
  name: PixelName;
  className?: string;
}): ReactNode {
  const rows = SHAPES[name];
  return (
    <svg
      viewBox="0 0 8 8"
      className={className}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {rows.map((row, y) =>
        row.split("").map((cell, x) =>
          cell === "#" ? (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />
          ) : null
        )
      )}
    </svg>
  );
}

